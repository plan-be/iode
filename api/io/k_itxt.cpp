/*
    Reads a txt file with the following description when loaded in excel
    this is the format generated by the Belgostat program
*/


int ImportObjsTXT::read_header(YYFILE* yy, Sample* smpl)
{
    memcpy(&TXT_smpl, smpl, sizeof(Sample));
    TXT_freq = (TXT_smpl.start_period).periodicity;
    TXT_nbper = get_nb_periods_per_year(TXT_smpl.start_period.periodicity);
    if(TXT_nbper < 0) 
    {
        kerror(0, "Please specify FROM and TO period");
        return -1;
    }

    TXT_fd = yy->yy_fd;
    return 0;
}

int ImportObjsTXT::read_value(char* date, int* shift, char* tval, double* dval)
{
    char    buf[21], y[5], m[3];
    int     pos;
    long    ly, lm;

    SCR_strlcpy((unsigned char*) y, (unsigned char*) date, 4);
    y[4] = 0;
    ly = atoi(y);        /* JMP 13-02-2013 */
    SCR_strlcpy((unsigned char*) m, (unsigned char*) date + 4, 2);
    m[2] = 0;
    lm = atoi(m);    /* JMP 13-02-2013 */

    switch(TXT_freq) {
        case 'Q' :
            lm = 1 + lm/4;
            break; /* JMP 05-10-00 */
        case 'Y' :
            lm = lm/12;
            break;
    }

    sprintf(buf, "%ld%c%ld", ly, TXT_freq, lm);
    Period* per = new Period(std::string(buf));
    *shift = per->difference(TXT_smpl.start_period);
    delete per;
    per = nullptr;

    pos = U_pos(',', (unsigned char*) tval);
    if(pos>=0) tval[pos] = '.';

    *dval= atof(tval);
    
    return 0;
}

int ImportObjsTXT::read_numerical_value(YYFILE* yy, char* name, int* shift, double* vector)
{
    char    buf[257];
    long    nbper;
    std::vector<std::string> tbl;

    while(1) {
        if(fgets(buf, 256, TXT_fd) == NULL)  return -1;
        tbl = split_skip_empty(std::string(buf), "; ");
        if(tbl.size() != 6)
            continue;
        /* The same periodicity */
        nbper = atoi(tbl[2].c_str());
        if(nbper != TXT_nbper)
            continue;
        else break;
    }

    SCR_strlcpy((unsigned char*) name, (unsigned char*) tbl[1].c_str(), 79); /* JMP 13-02-2013 */
    read_value(tbl[3].data(), shift, tbl[4].data(), vector);
    return 0;
}


